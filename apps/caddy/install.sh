# Sourced by build-disk.sh: installs Caddy's official static linux_amd64
# build from its GitHub releases, coreutils' env to point its state
# directories at /var/lib, and that directory.
#
# The build asks GitHub for the latest release and checks the download
# against the release's SHA-512 checksums. Set CADDY_VERSION (e.g. 2.11.9) to
# pin a version instead. Each version is kept in $WORKDIR/caddy/<version>/,
# so rebuilding doesn't download it again, and a pinned version that's there
# builds offline.
#
# Set CADDY_DOMAIN (e.g. www.example.com) to serve that name over HTTPS with
# a certificate Caddy gets from Let's Encrypt at boot, instead of plain HTTP
# on :80. The domain's DNS must point at the VM, with public ports 80 and/or
# 443 reaching the guest's 80 and 443, for the ACME challenge to succeed.
# CADDY_EMAIL sets the ACME account email (optional). CADDY_ACME_CA=staging
# uses Let's Encrypt's staging CA, which has looser rate limits but issues
# certificates browsers don't trust. Certificates live in /var/lib/caddy, so
# every rebuild of the disk requests a new one.
#
# Set CADDY_SSH=1 to also run OpenSSH, as apps/sshd does, so the site in
# /var/www can be updated with scp or sftp.
# SSH_AUTHORIZED_KEYS then names the public key file allowed to log in as root.
# Without it /root/.ssh/authorized_keys is left empty, for a platform such as
# microVM Cloud that adds the key when it deploys the VM. The host key is
# shared with apps/sshd, in $WORKDIR/ssh_host_ed25519_key.

require curl
require sha512sum coreutils
require tar

case "${CADDY_SSH:-}" in
    ""|0) caddy_ssh="" ;;
    1) caddy_ssh=1 ;;
    *) echo "CADDY_SSH must be unset, 0 or 1" >&2; exit 1 ;;
esac

caddy_version="${CADDY_VERSION:-}"
if [ -z "$caddy_version" ]; then
    # GitHub redirects .../releases/latest to .../releases/tag/v<version>.
    # This avoids the API, which limits unauthenticated clients to 60
    # requests an hour.
    latest="$(curl -fsS -m 30 -o /dev/null -w '%{redirect_url}' \
        https://github.com/caddyserver/caddy/releases/latest)" || {
        echo "Couldn't reach GitHub to find the latest Caddy." >&2
        echo "Set CADDY_VERSION to a version kept in $WORKDIR/caddy to build offline." >&2
        exit 1
    }
    caddy_version="${latest##*/v}"
fi
caddy_version="${caddy_version#v}"
# It becomes part of a URL and a path.
[[ "$caddy_version" =~ ^[0-9]+\.[0-9]+\.[0-9]+(-[A-Za-z0-9.]+)?$ ]] || {
    echo "Not a Caddy version: '$caddy_version'" >&2
    exit 1
}

caddy_dir="$WORKDIR/caddy/$caddy_version"
if [ ! -x "$caddy_dir/caddy" ]; then
    log "Downloading Caddy $caddy_version from GitHub"
    url="https://github.com/caddyserver/caddy/releases/download/v$caddy_version"
    tarball="caddy_${caddy_version}_linux_amd64.tar.gz"
    # Left behind by a build that failed partway.
    rm -rf "$WORKDIR"/caddy_download.*
    dl="$(mktemp -d "$WORKDIR/caddy_download.XXXXXX")"
    curl -fsSL -m 300 -o "$dl/$tarball" "$url/$tarball"
    curl -fsSL -m 30 -o "$dl/checksums.txt" "$url/caddy_${caddy_version}_checksums.txt"
    # A tarball that doesn't match, or has no line, fails the build here.
    grep " $tarball\$" "$dl/checksums.txt" | (cd "$dl" && sha512sum --check --quiet --strict)
    # Only the binary: the tarball also holds the licence and README.
    tar -xzf "$dl/$tarball" -C "$dl" caddy
    mkdir -p "$caddy_dir"
    mv "$dl/caddy" "$caddy_dir/caddy"
    rm -rf "$dl"
fi
log "Using Caddy $caddy_version"

mkdir -p "$ROOTFS/usr/bin"
cp "$caddy_dir/caddy" "$ROOTFS/usr/bin/caddy"
# The official build is static, so this finds nothing, unless that changes.
install_libs "$ROOTFS/usr/bin/caddy"
# init.conf lines can't set environment variables, so go through env.
install_binary "$(command -v env)"
mkdir -p "$ROOTFS/var/lib/caddy"

if [ -n "${CADDY_DOMAIN:-}" ]; then
    # It goes into the Caddyfile unquoted.
    [[ "$CADDY_DOMAIN" =~ ^[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?$ ]] || {
        echo "Not a domain name: '$CADDY_DOMAIN'" >&2
        exit 1
    }
    [[ "${CADDY_EMAIL:-}" =~ ^[^[:space:]{}\"]*$ ]] || {
        echo "Not an email address: '$CADDY_EMAIL'" >&2
        exit 1
    }
    case "${CADDY_ACME_CA:-}" in
        "") acme_ca="" ;;
        staging) acme_ca="https://acme-staging-v02.api.letsencrypt.org/directory" ;;
        *) echo "CADDY_ACME_CA must be unset or 'staging'" >&2; exit 1 ;;
    esac
    log "Serving https://$CADDY_DOMAIN/ with an ACME certificate"
    # Caddy needs DNS and the CA roots to reach Let's Encrypt.
    cp --parents -L /etc/ssl/certs/ca-certificates.crt "$ROOTFS"
    printf 'nameserver 1.1.1.1\nnameserver 8.8.8.8\n' >"$ROOTFS/etc/resolv.conf"
    {
        echo "# Generated by apps/caddy/install.sh for CADDY_DOMAIN=$CADDY_DOMAIN."
        echo "{"
        echo "	admin off"
        [ -n "${CADDY_EMAIL:-}" ] && echo "	email $CADDY_EMAIL"
        [ -n "$acme_ca" ] && echo "	acme_ca $acme_ca"
        echo "}"
        echo
        # Caddy also listens on :80 to answer HTTP-01 challenges and redirect
        # to HTTPS.
        echo "$CADDY_DOMAIN {"
        echo "	root * /var/www"
        echo "	file_server"
        echo "	encode gzip"
        echo "	log {"
        echo "		output stderr"
        echo "		format console"
        echo "	}"
        echo "}"
    } >"$ROOTFS/etc/caddy/Caddyfile"
fi

if [ -n "$caddy_ssh" ]; then
    log "Adding OpenSSH for root logins"
    # Warn here rather than leave it to apps/sshd, whose warning names its
    # own build command.
    if [ -z "${SSH_AUTHORIZED_KEYS:-}" ]; then
        echo "WARNING: no SSH_AUTHORIZED_KEYS given, so /root/.ssh/authorized_keys is empty." >&2
        echo "  Nobody can log in until a key is added, e.g. by the platform at deploy time." >&2
        echo "  To build one in: CADDY_SSH=1 SSH_AUTHORIZED_KEYS=~/.ssh/id_ed25519.pub ./build-disk.sh caddy" >&2
        SSH_AUTHORIZED_KEYS="$WORKDIR/blank.pub"
        : >"$SSH_AUTHORIZED_KEYS"
    fi
    # apps/sshd's install.sh doesn't bring its rootfs/: the sshd user and
    # nogroup it runs the pre-auth side as, root's login shell, the config and
    # DNS for ssh and curl out of the VM.
    for f in passwd group resolv.conf ssh/sshd_config; do
        install -D -m 644 "$SCRIPT_DIR/apps/sshd/rootfs/etc/$f" "$ROOTFS/etc/$f"
    done
    # shellcheck source=../sshd/install.sh
    source "$SCRIPT_DIR/apps/sshd/install.sh"
    # respawn, not once as in apps/sshd: caddy's respawn keeps the VM up
    # anyway, and a stopped sshd would otherwise lock everyone out.
    {
        echo
        echo "# From CADDY_SSH=1. sshd stays in the foreground (-D) and logs to the console (-e)."
        echo "respawn /usr/sbin/sshd -D -e"
    } >>"$ROOTFS/etc/init.conf"
    # caddy and the shell's commands fill all but 2MB of 128M, which leaves no
    # room to upload a site.
    DISK_SIZE=256M
fi
